// Regenerates the typed REST client types from the spec:
//   src/api/admin.d.ts     <- openapi/node-admin.yaml   (brand admin + portal API)
//   src/api/protocol.d.ts  <- openapi/obx-protocol.yaml (public access-request form)
// Usage: npm run gen:api [-- path-to-spec]   (default: ../spec)
//
// Post-processing: the CSRF header is marked required in the spec, but the client adds it
// in one middleware (src/api/client.ts), so callers never pass it by hand.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const spec = resolve(process.argv[2] ?? '../spec')
const bin = resolve('node_modules/.bin/openapi-typescript')
const jobs = [
  [join(spec, 'openapi/node-admin.yaml'), 'src/api/admin.d.ts'],
  [join(spec, 'openapi/obx-protocol.yaml'), 'src/api/protocol.d.ts'],
]
for (const [input, output] of jobs) {
  execFileSync(bin, [input, '-o', output, '--root-types', '--root-types-no-schema-prefix'], { stdio: 'inherit' })
  let src = readFileSync(output, 'utf8')
  src = src.replaceAll('"X-CSRF-Token": components["parameters"]["Csrf"];', '"X-CSRF-Token"?: components["parameters"]["Csrf"];')
  // A header block whose members are all optional becomes optional itself.
  src = src.replace(/(\n\s+)header: \{([^{}]*)\};/g, (m, indent, inner) =>
    /\n\s+"?[\w-]+"?: /.test(inner) ? m : `${indent}header?: {${inner}};`,
  )
  writeFileSync(output, '/* eslint-disable */\n// Generated by scripts/gen-api.mjs from the OBX spec. Do not edit.\n' + src)
}
